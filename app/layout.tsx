"use client";

import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import Header from "@/components/layout/Header";
import Footer from "@/components/layout/Footer";
import { useEffect, useState } from "react";
import { useAuthStore } from "@/store/auth";
import { getMe, UserData } from "@/api/users/me/getMe";
import { useUserStore } from "@/store/user";
import { AxiosError, HttpStatusCode } from "axios";
import { useRouter } from "next/navigation";
import LoadingScreen from "@/components/ui/Loading/Screen";
import { getMyAppointments } from "@/api/appointments/getMyAppointments";
import { useMyAppointmentsStore } from "@/store/myAppointments";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// export const metadata: Metadata = {
//   title: "Create Next App",
//   description: "Generated by create next app",
// };

export default function RootLayout({ children }: LayoutProps<"/">) {
  const router = useRouter();

  const update = useAuthStore((state) => state.update);

  const setAuth = useAuthStore((state) => state.setAuthData);

  const authificated = useAuthStore((state) => state.authificated);
  const setAuthificated = useAuthStore((state) => state.setAuthificated);

  const setUser = useUserStore((state) => state.setData);

  const updateAppointmnets = useMyAppointmentsStore((state) => state.update);

  const [loading, setLoading] = useState(true);

  const handleSucess = (data: UserData) => {
    setAuthificated(true);
    setUser(data);

    updateAppointmnets()
      .then(() => setLoading(false))
      .catch(() => setLoading(false));
  };

  const handleError = () => {
    setAuthificated(false);
    setAuth(undefined);
    setUser(undefined);

    setLoading(false);
    router.replace("/auth/login");
  };

  useEffect(() => {
    const data = update();

    if (authificated) {
      setLoading(false);
      return;
    }

    if (!data?.access_token || !data?.refresh_token) {
      setAuthificated(false);
      setLoading(false);

      return;
    }

    getMe().then(handleSucess).catch(handleError);
  }, [authificated]);

  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-screen flex flex-col">
        <Header />
        {loading ? (
          <LoadingScreen />
        ) : (
          <main className="flex-1">{children}</main>
        )}
        <Footer />
      </body>
    </html>
  );
}
